// Local-only UI fixture: no patient services or model providers are contacted.
// Run from frontend: node tests/preview-fixture.mjs
import { createServer } from 'vite'
import { createReadStream } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
process.chdir(root)
const requests = []
const patients = [
  { id: 'qa-001', name: 'Alex Morgan', age: '53', sex: 'M', status: 'review', files: [] },
  { id: 'qa-002', name: 'Sam Rivera', age: '61', sex: 'F', status: 'stable', files: [] },
]
const sources = [{ type: 'guideline', source: 'JCH-23-1637', title: '2020 Clinical practice guidelines for the management of hypertension in the Philippines', page: 2 }]
const server = await createServer({ root, configFile: path.join(root, 'vite.config.js'), server: { host: '127.0.0.1', port: 3101, strictPort: true }, plugins: [{
  name: 'clara-ui-fixtures', configureServer(server) {
    server.middlewares.use(async (req, res, next) => {
      if (!req.url.startsWith('/api/')) return next()
      const url = new URL(req.url, 'http://localhost')
      let raw = ''
      for await (const chunk of req) raw += chunk
      const body = raw ? JSON.parse(raw) : {}
      requests.push({ path: url.pathname, ...body })
      const json = data => { res.setHeader('Content-Type', 'application/json'); res.end(JSON.stringify(data)) }
      if (url.pathname === '/api/qa/requests') return json(requests)
      if (url.pathname.endsWith('/patients')) return json({ patients })
      if (url.pathname.endsWith('/documents/guideline')) {
        if (url.searchParams.get('source') !== 'JCH-23-1637') { res.statusCode = 404; return res.end() }
        res.setHeader('Content-Type', 'application/pdf')
        return createReadStream(path.join(root, '../ai-services/guidelines/JCH-23-1637.pdf')).pipe(res)
      }
      if (url.pathname.endsWith('/chat/stream')) {
        res.setHeader('Content-Type', 'text/event-stream'); res.setHeader('Cache-Control', 'no-cache')
        const event = data => { if (!res.destroyed) res.write(`data: ${JSON.stringify(data)}\n\n`) }
        const activeSources = /missing/i.test(body.message) ? [{ ...sources[0], source: 'unavailable.pdf' }] : sources
        event({ type: 'status', label: 'Reading patient PDF source' })
        const timer1 = setTimeout(() => {
          event({ type: 'sources', sources: activeSources })
          event({ type: 'status', label: 'Integrating retrieved clinical information' })
        }, 700)
        const timer2 = setTimeout(() => {
          if (/error/i.test(body.message)) { event({ type: 'error', message: 'Synthetic service failure' }); return res.end() }
          event({ type: 'meta', sources: activeSources, guidelines_used: true })
          event({ type: 'status', label: 'Writing the response' })
          event({ type: 'token', token: '**Source review**\n\nThis is a synthetic conversation for interface testing. The accompanying preview opens the cited guideline on PDF page 2.\n\n- Conversation history is retained.\n- Source pages can be inspected directly.\n\nNo clinical advice is generated by this test.' })
          event({ type: 'done', elapsed_ms: 2200 }); res.end()
        }, /slow/i.test(body.message) ? 15000 : 2200)
        res.on('close', () => { clearTimeout(timer1); clearTimeout(timer2) })
        return
      }
      if (url.pathname.endsWith('sync/status')) return json({ events: [] })
      if (url.pathname.endsWith('discharge-list')) return json({ files: [] })
      if (url.pathname.endsWith('vitals-timeline')) return json({ timeline: [] })
      if (url.pathname.endsWith('-results')) return json({ results: [] })
      return json({})
    })
  },
}] })
await server.listen()
console.log('CLARA isolated UI fixture: http://127.0.0.1:3101')
